import type { ReplayPremierePolicyIdentityView } from "src/client/ReplayPremiereOverlay";

/**
 * Client-side fetch + join layer for the public league mirror
 * (`/ai-league-runs/league/data.json`) — the "who are these four and which
 * should I back" context the league scouting panel renders (see
 * `components/LeagueContextPanel.ts`).
 *
 * This is a SEPARATE artifact from the premiere's own bootstrap/market feed:
 * fetched once per page load, never polled, and never wired to
 * `aria-live` — unlike prices, a player's rating does not tick on a 1-3s
 * cadence, so there is nothing here that needs a live region (a per-tick
 * `aria-live` was already rejected for exactly that spam reason).
 *
 * Parsing is defensive rather than a trusting `as` cast: this file is
 * generated by a separate process (`coworld-league-mirror.ts`) this page
 * does not control, so a half-written or reshaped snapshot must degrade to
 * "missing" per-row rather than throwing or rendering a confidently-wrong
 * number. See `parseLeagueData`.
 */

export const LEAGUE_DATA_URL = "/ai-league-runs/league/data.json";

export interface LeagueStandingRow {
  readonly rank: number;
  readonly playerName: string;
  readonly ratingPolicyLabel: string | null;
  readonly activeChampionPolicyLabel: string | null;
  readonly policyLabel: string | null;
  readonly score: number | null;
  readonly roundsPlayed: number | null;
  readonly isHouse: boolean;
}

export interface LeagueEpisodePlayerRow {
  readonly name: string;
  readonly isAlive: boolean;
  readonly isWinner: boolean;
}

export interface LeagueEpisodeRow {
  readonly episodeRequestId: string;
  readonly roundNumber: number | null;
  readonly completedAt: string | null;
  readonly players: readonly LeagueEpisodePlayerRow[];
}

export interface LeagueDataSnapshot {
  readonly generatedAt: string | null;
  readonly lastGoodSyncAt: string | null;
  readonly stale: boolean;
  readonly standings: readonly LeagueStandingRow[];
  /** Newest-first (sorted here, never trusted from the server — see module doc). */
  readonly episodes: readonly LeagueEpisodeRow[];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function asNullableString(value: unknown): string | null {
  return typeof value === "string" ? value : null;
}

function asNullableNumber(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function parseStanding(value: unknown): LeagueStandingRow | null {
  if (
    !isRecord(value) ||
    typeof value.playerName !== "string" ||
    typeof value.rank !== "number"
  ) {
    return null;
  }
  return {
    rank: value.rank,
    playerName: value.playerName,
    ratingPolicyLabel: asNullableString(value.ratingPolicyLabel),
    activeChampionPolicyLabel: asNullableString(value.activeChampionPolicyLabel),
    policyLabel: asNullableString(value.policyLabel),
    score: asNullableNumber(value.score),
    roundsPlayed: asNullableNumber(value.roundsPlayed),
    isHouse: value.isHouse === true,
  };
}

function parseEpisodePlayer(value: unknown): LeagueEpisodePlayerRow | null {
  if (!isRecord(value) || typeof value.name !== "string") return null;
  return {
    name: value.name,
    isAlive: value.isAlive === true,
    isWinner: value.isWinner === true,
  };
}

function parseEpisode(value: unknown): LeagueEpisodeRow | null {
  if (
    !isRecord(value) ||
    typeof value.episodeRequestId !== "string" ||
    !Array.isArray(value.players)
  ) {
    return null;
  }
  const players = value.players
    .map(parseEpisodePlayer)
    .filter((p): p is LeagueEpisodePlayerRow => p !== null);
  if (players.length === 0) return null;
  return {
    episodeRequestId: value.episodeRequestId,
    roundNumber: asNullableNumber(value.roundNumber),
    completedAt: asNullableString(value.completedAt),
    players,
  };
}

/**
 * Parses a fetched `data.json` body into a snapshot, dropping malformed
 * rows individually instead of throwing. Returns `null` only when the
 * top-level shape itself is unusable (e.g. not an object, or missing the
 * arrays entirely) — the caller renders that as "league data unavailable".
 */
export function parseLeagueData(value: unknown): LeagueDataSnapshot | null {
  if (
    !isRecord(value) ||
    !Array.isArray(value.standings) ||
    !Array.isArray(value.episodes)
  ) {
    return null;
  }
  const standings = value.standings
    .map(parseStanding)
    .filter((s): s is LeagueStandingRow => s !== null);
  const episodes = value.episodes
    .map(parseEpisode)
    .filter((e): e is LeagueEpisodeRow => e !== null)
    .sort((a, b) => {
      const at = a.completedAt === null ? -Infinity : Date.parse(a.completedAt);
      const bt = b.completedAt === null ? -Infinity : Date.parse(b.completedAt);
      return bt - at;
    });
  return {
    generatedAt: asNullableString(value.generatedAt),
    lastGoodSyncAt: asNullableString(value.lastGoodSyncAt),
    stale: value.stale === true,
    standings,
    episodes,
  };
}

let cached: Promise<LeagueDataSnapshot | null> | null = null;

/**
 * Fetches and parses the public league mirror once per page load (module-
 * level cache — every panel instance on the page shares one request). A
 * network failure, non-200, or unparseable body resolves to `null` rather
 * than rejecting, so callers render a plain "unavailable" state instead of
 * an unhandled rejection tearing down the trading sheet around it.
 */
export function fetchLeagueData(
  fetchImpl: typeof fetch = fetch,
): Promise<LeagueDataSnapshot | null> {
  if (cached !== null) return cached;
  cached = fetchImpl(LEAGUE_DATA_URL, { headers: { accept: "application/json" } })
    .then((res) => (res.ok ? (res.json() as Promise<unknown>) : null))
    .then((body) => (body === null ? null : parseLeagueData(body)))
    .catch(() => null);
  return cached;
}

/** Test-only: clears the module-level fetch cache between test cases. */
export function resetLeagueDataCacheForTests(): void {
  cached = null;
}

/**
 * A seat this panel can look up — the minimal slice of `MarketSeatOption`
 * it needs, kept structural so callers don't have to import the full type.
 */
export interface LeagueLookupSeat {
  readonly displayName: string;
  readonly policyIdentity?: ReplayPremierePolicyIdentityView;
}

/**
 * Joins a premiere seat to a league standings row. Per RealRoster's
 * confirmed contract: a seat is a real league agent iff its verified
 * `policyIdentity.namespace === "softmax_policy_version"` (a `local_manifest`
 * seat is a synthetic/exhibition persona and never maps to standings). When
 * mapped, `displayName` is the league `playerName` and
 * `policyIdentity.policyName` is the league `policyLabel` — matched first by
 * policy label (exact build), falling back to player name (current rating)
 * if the seat's specific build has aged out of the label fields the mirror
 * currently reports. Returns `null` — never a fabricated/zeroed row — for
 * any seat that isn't a real league agent or isn't found in standings.
 */
export function resolveSeatStanding(
  data: LeagueDataSnapshot,
  seat: LeagueLookupSeat,
): LeagueStandingRow | null {
  const identity = seat.policyIdentity;
  if (identity === undefined || identity.namespace !== "softmax_policy_version") {
    return null;
  }
  const policyLabel = identity.policyName;
  const byPolicy = data.standings.find(
    (s) =>
      s.policyLabel === policyLabel ||
      s.ratingPolicyLabel === policyLabel ||
      s.activeChampionPolicyLabel === policyLabel,
  );
  if (byPolicy !== undefined) return byPolicy;
  return data.standings.find((s) => s.playerName === seat.displayName) ?? null;
}

export type FormOutcome = "won" | "eliminated" | "survived";

export interface FormEntry {
  readonly episodeRequestId: string;
  readonly completedAt: string | null;
  readonly roundNumber: number | null;
  readonly outcome: FormOutcome;
}

/**
 * The last `limit` league rounds (newest first) a player appears in,
 * regardless of who else was seated — a high rating that has been losing
 * lately is exactly the edge an attentive trader should be able to find
 * (Target, priority 2).
 */
export function recentForm(
  data: LeagueDataSnapshot,
  playerName: string,
  limit = 5,
): readonly FormEntry[] {
  const entries: FormEntry[] = [];
  for (const episode of data.episodes) {
    const player = episode.players.find((p) => p.name === playerName);
    if (player === undefined) continue;
    entries.push({
      episodeRequestId: episode.episodeRequestId,
      completedAt: episode.completedAt,
      roundNumber: episode.roundNumber,
      outcome: player.isWinner ? "won" : player.isAlive ? "survived" : "eliminated",
    });
    if (entries.length >= limit) break;
  }
  return entries;
}

export interface HeadToHeadRecord {
  readonly meetings: number;
  readonly subjectWins: number;
  readonly opponentWins: number;
}

/**
 * How often two players have shared a league round before, and who won
 * when both were present. League rounds are FFA matches (typically many
 * more than 2 seats), so this is "shared match history", not a literal
 * 1-on-1 ledger — the panel's copy says "met before", never "head-to-head
 * wins", to stay honest about that.
 */
export function headToHead(
  data: LeagueDataSnapshot,
  subjectPlayerName: string,
  opponentPlayerName: string,
): HeadToHeadRecord {
  let meetings = 0;
  let subjectWins = 0;
  let opponentWins = 0;
  for (const episode of data.episodes) {
    const subject = episode.players.find((p) => p.name === subjectPlayerName);
    const opponent = episode.players.find((p) => p.name === opponentPlayerName);
    if (subject === undefined || opponent === undefined) continue;
    meetings += 1;
    if (subject.isWinner) subjectWins += 1;
    if (opponent.isWinner) opponentWins += 1;
  }
  return { meetings, subjectWins, opponentWins };
}
